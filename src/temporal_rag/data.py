def load_events(path: str | Path) -> list[Event]:
    """Import a bounded JSON array; event metadata is application-owned input."""
    path = Path(path)
    if path.stat().st_size > 10_000_000:
        raise TemporalError("input_too_large", "Event file exceeds 10 MB")
    try:
        # Bound the actual read as well as stat(), including files changed mid-read.
        with path.open("rb") as stream:
            payload = stream.read(10_000_001)
        if len(payload) > 10_000_000:
            raise TemporalError("input_too_large", "Event file exceeds 10 MB")

        def unique_object(pairs):
            result = {}
            for key, value in pairs:
                if key in result:
                    raise TemporalError("invalid_event", "Duplicate JSON fields are forbidden")
                result[key] = value
            return result

        rows = json.loads(payload.decode("utf-8"), object_pairs_hook=unique_object)
        if not isinstance(rows, list) or len(rows) > MAX_EVENTS:
            raise TemporalError("invalid_event", "Expected an array containing at most 5000 events")
        events = [Event(**row) for row in rows]
    except (TypeError, json.JSONDecodeError, UnicodeError, RecursionError) as exc:
        raise TemporalError("invalid_event", "Invalid event JSON schema") from exc
    EventStore(events)
    return events
